const COPY = { it, en };

export type Msg = keyof typeof it;

export function t(lang: UiLang, key: Msg, vars?: Record<string, string | number>): string {
  let text: string = COPY[lang][key] ?? COPY.it[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.split(`{${name}}`).join(String(value));
    }
  }
  return text;
}
